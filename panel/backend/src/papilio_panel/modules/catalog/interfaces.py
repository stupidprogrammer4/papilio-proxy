"""Catalogue application and aggregate persistence boundaries."""

from typing import Protocol
from uuid import UUID

from .domain import (
    ProductChange,
    ProductCreate,
    ProductCreation,
    ProductOfferRead,
    ProductPage,
    ProductRead,
    ProductSearch,
)


class ProductStorage(Protocol):
    def create(self, values: ProductCreate, user_level: int) -> ProductCreation: ...
    def change(self, values: ProductChange, user_level: int) -> ProductRead: ...
    def read(self, product_id: UUID, actor_id: int) -> ProductRead: ...
    def read_offer(self, offer_id: UUID, actor_id: int) -> ProductOfferRead: ...
    def search(self, values: ProductSearch) -> ProductPage: ...


class ProductCapability(Protocol):
    def create(self, values: ProductCreate) -> ProductCreation: ...
    def change(self, values: ProductChange) -> ProductRead: ...
    def read(self, product_id: UUID, actor_id: int) -> ProductRead: ...
    def read_offer(self, offer_id: UUID, actor_id: int) -> ProductOfferRead: ...
    def search(self, values: ProductSearch) -> ProductPage: ...
