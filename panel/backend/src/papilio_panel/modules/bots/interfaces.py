"""Explicit ownership, persistence, pairing and Telegram transport boundaries."""

from typing import Protocol
from uuid import UUID

from .domain import (
    BotChange,
    BotCompletion,
    BotCreate,
    BotCreation,
    BotDefaults,
    BotInspection,
    BotPage,
    BotPollClaim,
    BotPollResult,
    BotRead,
    BotSearch,
    PairingGrant,
    PairingSecret,
    PairingState,
    TelegramConnection,
    UpdateBatch,
)


class BotStorage(Protocol):
    def create(self, values: BotCreate, input_digest: str, token_digest: str) -> BotCreation: ...
    def read(self, bot_id: UUID, actor_id: int) -> BotRead: ...
    def search(self, values: BotSearch) -> BotPage: ...
    def change(self, values: BotChange, token_digest: str | None = None) -> BotRead: ...
    def set_pairing(self, bot: BotRead, secret: PairingSecret) -> None: ...
    def claim(self, bot_id: UUID) -> BotPollClaim | None: ...
    def pairing_state(self, claim: BotPollClaim) -> PairingState: ...
    def identity_registration(self, telegram_id: int) -> UUID | None: ...
    def complete(self, claim: BotPollClaim, result: BotPollResult) -> BotCompletion: ...
    def fail(
        self, claim: BotPollClaim, error_code: str, retry_after_seconds: int | None = None
    ) -> None: ...


class TelegramGateway(Protocol):
    def inspect(self, connection: TelegramConnection) -> BotInspection: ...
    def updates(self, connection: TelegramConnection, next_update_id: int) -> UpdateBatch: ...


class PairingIssuer(Protocol):
    def issue(self, lifetime_seconds: int) -> PairingSecret: ...


class BotCapability(Protocol):
    def defaults(self, actor_id: int) -> BotDefaults: ...
    def create(self, values: BotCreate) -> BotRead: ...
    def read(self, bot_id: UUID, actor_id: int) -> BotRead: ...
    def search(self, values: BotSearch) -> BotPage: ...
    def change(self, values: BotChange) -> BotRead: ...
    def pair(self, bot_id: UUID, actor_id: int) -> PairingGrant: ...


class BotPollingCapability(Protocol):
    def poll(self, bot_id: UUID) -> None: ...
