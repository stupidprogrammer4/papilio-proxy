"""Distinct purchase orchestration and order read contracts."""

from typing import Protocol
from uuid import UUID

from .domain import OrderCreation, OrderPage, OrderRead, OrderSearch, PurchaseInput, PurchaseTerms


class OrderStorage(Protocol):
    def find_request(self, actor_id: int, request_key: UUID) -> OrderRead | None: ...
    def reserve(self, values: PurchaseInput, terms: PurchaseTerms) -> OrderCreation: ...
    def complete_purchase(
        self, order_id: UUID, actor_id: int, service_id: UUID, wallet_entry_id: UUID | None
    ) -> OrderRead: ...
    def read(self, order_id: UUID, actor_id: int) -> OrderRead: ...
    def search(self, values: OrderSearch) -> OrderPage: ...


class OrderPurchaseCapability(Protocol):
    def purchase(self, values: PurchaseInput) -> OrderCreation: ...


class OrderReadCapability(Protocol):
    def read(self, order_id: UUID, actor_id: int) -> OrderRead: ...
    def search(self, values: OrderSearch) -> OrderPage: ...
