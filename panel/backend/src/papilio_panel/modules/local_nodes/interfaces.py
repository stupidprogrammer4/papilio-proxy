"""Explicit registration and persistence boundaries for the bundled runtime."""

from typing import Protocol
from uuid import UUID

from papilio_panel.modules.identity.domain import OwnerIdentity

from .domain import (
    DeliveryRead,
    DeliveryUpdate,
    LocalAttempt,
    LocalBinding,
    LocalBootstrap,
    LocalClaim,
    LocalCreate,
    LocalCreation,
    LocalDefaults,
    LocalDelivery,
    LocalOperationRead,
    LocalRead,
    LocalRetry,
    LocalWork,
    OwnerInitialization,
)


class LocalStorage(Protocol):
    def current(self, actor_id: int) -> LocalRead | None: ...
    def create(self, values: LocalBinding) -> LocalCreation: ...
    def update_delivery(self, values: DeliveryUpdate) -> DeliveryRead: ...
    def retry(self, values: LocalRetry) -> LocalOperationRead: ...
    def read_operation(self, operation_id: UUID, actor_id: int) -> LocalOperationRead: ...


class LocalNodeCapability(Protocol):
    def defaults(self) -> LocalDefaults: ...
    def read(self, actor_id: int) -> LocalRead: ...
    def update_delivery(self, values: DeliveryUpdate) -> DeliveryRead: ...
    def retry(self, values: LocalRetry) -> LocalOperationRead: ...
    def read_operation(self, operation_id: UUID, actor_id: int) -> LocalOperationRead: ...


class LocalRegistrationCapability(Protocol):
    def create(self, values: LocalCreate) -> LocalCreation: ...


class LocalConfiguration(Protocol):
    def defaults(self) -> LocalDefaults: ...


class LocalOwnerInitializationCapability(Protocol):
    def complete(self, values: OwnerInitialization) -> OwnerIdentity: ...


class LocalFiles(Protocol):
    def publish(self, values: LocalBootstrap) -> None: ...


class LocalWorkStorage(Protocol):
    def read(self, operation_id: UUID) -> LocalWork: ...
    def claim(self, operation_id: UUID) -> LocalClaim | None: ...
    def active(self, claim: LocalClaim) -> bool: ...
    def finish(self, claim: LocalClaim, error_code: str | None, *, retryable: bool) -> None: ...
    def release(self, claim: LocalClaim) -> None: ...
    def pending(self) -> LocalDelivery | None: ...
    def dispatched(self, delivery: LocalDelivery) -> None: ...


class LocalDeliverySchedule(Protocol):
    def enabled(self) -> bool: ...


class LocalPublisher(Protocol):
    def publish(self, delivery: LocalDelivery) -> None: ...


class LocalPublicationCapability(Protocol):
    def dispatch(self) -> None: ...


class LocalExecutionCapability(Protocol):
    def begin(self, operation_id: UUID) -> LocalAttempt: ...
    def prepare(self, claim: LocalClaim) -> None: ...
    def reject(self, claim: LocalClaim, error_code: str, *, retryable: bool = False) -> None: ...
