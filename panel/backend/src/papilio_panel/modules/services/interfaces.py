"""Explicit persistent service, delivery and subscription provider boundaries."""

from typing import Protocol
from uuid import UUID

from papilio_panel.modules.cores.domain import XrayInboundRead

from .domain import (
    ServiceClaim,
    ServiceCreate,
    ServiceCreation,
    ServiceDelivery,
    ServiceOutcome,
    ServicePage,
    ServiceRead,
    ServiceSearch,
    SubscriptionGrant,
    XrayCredential,
)


class ServiceStorage(Protocol):
    def create(
        self, values: ServiceCreate, user_level: int, timeout_seconds: int
    ) -> ServiceCreation: ...
    def add_outbox(self, service_id: UUID) -> None: ...
    def read(self, service_id: UUID, actor_id: int) -> ServiceRead: ...
    def search(self, values: ServiceSearch) -> ServicePage: ...
    def claim(self, service_id: UUID) -> ServiceClaim: ...
    def finish(self, claim: ServiceClaim, error_code: str | None) -> None: ...
    def credential(self, service_id: UUID, actor_id: int) -> XrayCredential: ...
    def subscription_grant(self, service_id: UUID, actor_id: int) -> SubscriptionGrant: ...
    def read_grant(self, grant: SubscriptionGrant) -> ServiceRead: ...
    def pending_deliveries(self) -> tuple[ServiceDelivery, ...]: ...
    def mark_dispatched(self, deliveries: tuple[ServiceDelivery, ...]) -> None: ...


class SubscriptionTokens(Protocol):
    def issue(self, grant: SubscriptionGrant) -> str: ...
    def verify(self, token: str) -> SubscriptionGrant: ...


class SubscriptionOutput(Protocol):
    def render(self, name: str, endpoint: XrayInboundRead, credential: XrayCredential) -> bytes: ...


class ServicePublisher(Protocol):
    def publish(self, deliveries: tuple[ServiceDelivery, ...]) -> None: ...


class ServiceDeliverySchedule(Protocol):
    def enabled(self) -> bool: ...


class ServiceCapability(Protocol):
    def create(self, values: ServiceCreate) -> ServiceCreation: ...
    def read(self, service_id: UUID, actor_id: int) -> ServiceRead: ...
    def search(self, values: ServiceSearch) -> ServicePage: ...
    def subscription_token(self, service_id: UUID, actor_id: int) -> str: ...


class ServiceSubscriptionCapability(Protocol):
    def render(self, token: str) -> bytes: ...


class ServiceExecutionCapability(Protocol):
    def provision(self, service_id: UUID) -> ServiceOutcome: ...


class ServicePublicationCapability(Protocol):
    def dispatch(self) -> None: ...
