"""Explicit storage, execution and policy boundaries for native account synchronization."""

from typing import Protocol
from uuid import UUID

from .synchronization_contracts import (
    SynchronizationClaim,
    SynchronizationDelivery,
    SynchronizationRead,
    SynchronizationUpdate,
)


class ServiceSynchronizationStorage(Protocol):
    def read(self, service_id: UUID, actor_id: int) -> SynchronizationRead: ...
    def update(self, values: SynchronizationUpdate) -> SynchronizationRead: ...
    def claim(self, service_id: UUID, generation: int) -> SynchronizationClaim | None: ...
    def active(self, claim: SynchronizationClaim) -> bool: ...
    def finish(self, claim: SynchronizationClaim, error_code: str | None) -> None: ...
    def pending(self) -> tuple[SynchronizationDelivery, ...]: ...
    def dispatched(self, deliveries: tuple[SynchronizationDelivery, ...]) -> None: ...


class ServiceSynchronizationCapability(Protocol):
    def read(self, service_id: UUID, actor_id: int) -> SynchronizationRead: ...
    def update(self, values: SynchronizationUpdate) -> SynchronizationRead: ...


class ServiceSynchronizationExecutionCapability(Protocol):
    def begin(self, service_id: UUID, generation: int) -> SynchronizationClaim | None: ...
    def apply(self, claim: SynchronizationClaim) -> None: ...
    def reject(self, claim: SynchronizationClaim, error_code: str) -> None: ...


class ServiceSynchronizationPublisher(Protocol):
    def publish(self, deliveries: tuple[SynchronizationDelivery, ...]) -> None: ...


class ServiceSynchronizationPublicationCapability(Protocol):
    def dispatch(self) -> None: ...
