"""Identity application and persistence contracts."""

from typing import Protocol

from .domain import AdminPrincipal, OwnerIdentity, OwnerSetupInput


class OwnerSetupCapability(Protocol):
    def issue_token(self) -> str: ...

    def complete(self, values: OwnerSetupInput) -> OwnerIdentity: ...


class SetupStorage(Protocol):
    def is_configured(self) -> bool: ...

    def issue_grant(self) -> str: ...

    def claim_initialization(self) -> bool: ...

    def consume_grant(self, token: str) -> None: ...

    def create_owner(self, username: str, password: str) -> OwnerIdentity: ...

    def finish_initialization(self, owner: OwnerIdentity) -> None: ...


class AdminAccessCapability(Protocol):
    def authorize(self, principal: AdminPrincipal) -> None: ...

    def authorize_actor(self, actor_id: int) -> None: ...

    def permitted(self, actor_id: int) -> bool: ...

    def authorize_owner(self, actor_id: int) -> None: ...


class PrincipalStorage(Protocol):
    def read(self, actor_id: int) -> AdminPrincipal: ...


class CredentialValidation(Protocol):
    def validate(self, username: str, password: str) -> None: ...
