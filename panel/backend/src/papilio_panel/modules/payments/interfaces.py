"""Explicit payment configuration, invoice and evidence capabilities."""

from typing import Protocol
from uuid import UUID

from .domain import (
    DecisionInput,
    DecisionPage,
    DecisionRead,
    DecisionReservation,
    DecisionResult,
    DecisionSearch,
    InvoiceCreation,
    InvoiceIssue,
    InvoicePage,
    InvoiceRead,
    InvoiceSearch,
    InvoiceTransition,
    PaymentDefinition,
    PaymentSettingsChange,
    PaymentSettingsCreate,
    PaymentSettingsRead,
    ReceiptContent,
    ReceiptPage,
    ReceiptRead,
    ReceiptReservation,
    ReceiptSearch,
    ReceiptSubmit,
)


class PaymentSettingsStorage(Protocol):
    def create(self, values: PaymentSettingsCreate) -> PaymentSettingsRead: ...
    def read(self, actor_id: int) -> PaymentSettingsRead: ...
    def change(self, values: PaymentSettingsChange) -> PaymentSettingsRead: ...


class PaymentSettingsCapability(PaymentSettingsStorage, Protocol):
    """Settings operations authorize the current operator."""

    def defaults(self, actor_id: int) -> PaymentDefinition: ...


class InvoiceStorage(Protocol):
    def create(self, values: InvoiceIssue, settings: PaymentSettingsRead) -> InvoiceCreation: ...
    def find_request(self, actor_id: int, request_key: UUID) -> InvoiceRead | None: ...
    def read(self, invoice_id: UUID, actor_id: int) -> InvoiceRead: ...
    def search(self, values: InvoiceSearch) -> InvoicePage: ...
    def transition(self, values: InvoiceTransition) -> None: ...
    def reserve_receipt(self, values: ReceiptSubmit) -> ReceiptReservation: ...
    def read_receipt(self, receipt_id: UUID, invoice_id: UUID, actor_id: int) -> ReceiptRead: ...
    def receipt_file(self, receipt_id: UUID, invoice_id: UUID, actor_id: int) -> ReceiptContent: ...
    def receipts(self, values: ReceiptSearch) -> ReceiptPage: ...
    def reserve_decision(self, values: DecisionInput) -> DecisionReservation: ...
    def complete_decision(self, decision_id: UUID, actor_id: int, entry_id: UUID) -> None: ...
    def read_decision(self, decision_id: UUID, invoice_id: UUID, actor_id: int) -> DecisionRead: ...
    def decisions(self, values: DecisionSearch) -> DecisionPage: ...


class InvoiceCapability(Protocol):
    def issue(self, values: InvoiceIssue) -> InvoiceCreation: ...
    def read(self, invoice_id: UUID, actor_id: int) -> InvoiceRead: ...
    def search(self, values: InvoiceSearch) -> InvoicePage: ...


class ReceiptCapability(Protocol):
    def submit(self, values: ReceiptSubmit) -> ReceiptReservation: ...
    def read(self, receipt_id: UUID, invoice_id: UUID, actor_id: int) -> ReceiptRead: ...
    def file(self, receipt_id: UUID, invoice_id: UUID, actor_id: int) -> ReceiptContent: ...
    def search(self, values: ReceiptSearch) -> ReceiptPage: ...


class PaymentDecisionCapability(Protocol):
    def decide(self, values: DecisionInput) -> DecisionResult: ...


class PaymentDecisionHistoryCapability(Protocol):
    def search(self, values: DecisionSearch) -> DecisionPage: ...
