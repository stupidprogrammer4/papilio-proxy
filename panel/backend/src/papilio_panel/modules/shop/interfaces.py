"""Public shop policy and native persistence contracts."""

from datetime import datetime
from typing import Protocol
from uuid import UUID

from papilio_panel.modules.bots.domain import TelegramReply, TelegramSendResult

from .domain import (
    BindingReservation,
    InvoiceReplyLookup,
    MessageClaim,
    MessageRead,
    MessageState,
    PurchaseConfirmation,
    ReplyWrite,
    ShopCustomerContext,
    ShopDefinition,
    ShopSendOutcome,
    ShopSettingsChange,
    ShopSettingsCreate,
    ShopSettingsRead,
    WorkClaim,
    WorkDelivery,
    WorkRead,
)


class ShopSettingsStorage(Protocol):
    def read(self, bot_id: UUID, actor_id: int) -> ShopSettingsRead: ...
    def create(self, values: ShopSettingsCreate) -> ShopSettingsRead: ...
    def change(self, values: ShopSettingsChange) -> ShopSettingsRead: ...


class ShopControlCapability(Protocol):
    def defaults(self, actor_id: int) -> ShopDefinition: ...
    def read(self, bot_id: UUID, actor_id: int) -> ShopSettingsRead: ...
    def create(self, values: ShopSettingsCreate) -> ShopSettingsRead: ...
    def change(self, values: ShopSettingsChange) -> ShopSettingsRead: ...


class CustomerBindingStorage(Protocol):
    def reserve(self, owner_id: int, telegram_user_id: int) -> BindingReservation: ...
    def bind(self, binding_id: UUID, owner_id: int, customer_id: UUID) -> None: ...


class ShopCustomerCapability(Protocol):
    def register(self, event_id: int) -> ShopCustomerContext: ...


class ShopWorkStorage(Protocol):
    def discover(self) -> None: ...
    def read(self, work_id: UUID) -> WorkRead: ...
    def claim(self, work_id: UUID, lease_seconds: int) -> UUID | None: ...
    def complete(self, claim: WorkClaim, error_code: str | None = None) -> None: ...
    def release(self, claim: WorkClaim) -> None: ...
    def pending(self) -> tuple[WorkDelivery, ...]: ...
    def dispatched(self, deliveries: tuple[WorkDelivery, ...]) -> None: ...


class ShopMessageStorage(Protocol):
    def append(self, values: ReplyWrite) -> UUID: ...
    def reference(self, message_id: UUID) -> MessageRead: ...
    def read(self, message_id: UUID, bot_id: UUID, owner_id: int) -> MessageRead: ...
    def claim(
        self, message_id: UUID, settings: ShopSettingsRead, lease_seconds: int
    ) -> MessageClaim | None: ...
    def complete(
        self,
        claim: MessageClaim,
        result: TelegramSendResult,
        status: MessageState,
        retry_at: datetime | None,
    ) -> None: ...
    def expire(self, message_id: UUID, status: MessageState, retry_at: datetime | None) -> None: ...
    def release(self, claim: MessageClaim) -> None: ...
    def active(self, claim: MessageClaim) -> bool: ...
    def reject(self, message_id: UUID, error_code: str) -> None: ...
    def invoice_for_reply(self, values: InvoiceReplyLookup) -> UUID: ...
    def pending(self) -> tuple[WorkDelivery, ...]: ...
    def dispatched(self, deliveries: tuple[WorkDelivery, ...]) -> None: ...


class ShopPublisher(Protocol):
    def work(self, deliveries: tuple[WorkDelivery, ...]) -> None: ...
    def messages(self, deliveries: tuple[WorkDelivery, ...]) -> None: ...


class ShopDeliverySchedule(Protocol):
    def enabled(self) -> bool: ...


class ShopExecutionCapability(Protocol):
    def begin(self, work_id: UUID) -> WorkClaim | None: ...
    def process(self, claim: WorkClaim) -> None: ...
    def fail(self, claim: WorkClaim, code: str, reason: str) -> None: ...


class ShopMenuCapability(Protocol):
    def response(self, context: ShopCustomerContext) -> TelegramReply: ...


class PurchaseConfirmationStorage(Protocol):
    def reserve(self, values: PurchaseConfirmation) -> PurchaseConfirmation: ...
    def read(
        self, confirmation_id: UUID, bot_id: UUID, customer_id: UUID
    ) -> PurchaseConfirmation: ...
    def complete(self, confirmation: PurchaseConfirmation, order_id: UUID) -> None: ...


class ShopPurchaseCapability(Protocol):
    def select(
        self, context: ShopCustomerContext, work_id: UUID, product_id: UUID
    ) -> TelegramReply: ...
    def confirm(self, context: ShopCustomerContext, confirmation_id: UUID) -> TelegramReply: ...


class ShopOrderQueryCapability(Protocol):
    def search(self, context: ShopCustomerContext, page: int) -> TelegramReply: ...
    def read(self, context: ShopCustomerContext, order_id: UUID) -> TelegramReply: ...


class ShopSendingCapability(Protocol):
    def begin(self, message_id: UUID) -> MessageClaim | None: ...
    def send(self, claim: MessageClaim) -> ShopSendOutcome: ...
    def fail(self, claim: MessageClaim, error_code: str) -> ShopSendOutcome: ...


class ShopPublicationCapability(Protocol):
    def dispatch(self) -> None: ...
