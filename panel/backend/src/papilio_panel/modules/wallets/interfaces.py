"""Wallet accounting application and native persistence boundaries."""

from typing import Protocol
from uuid import UUID

from .domain import (
    BalanceChange,
    BalanceObservation,
    JournalEntryCreation,
    JournalEntryRead,
    JournalInput,
    JournalPage,
    JournalReservation,
    JournalSearch,
    WalletChange,
    WalletOpen,
    WalletOpening,
    WalletPost,
    WalletRead,
)


class WalletStorage(Protocol):
    def open(self, values: WalletOpen) -> WalletOpening: ...
    def read(self, customer_id: UUID, actor_id: int) -> WalletRead: ...
    def change(
        self, wallet_id: UUID, values: WalletChange, minimum_balance_minor: int
    ) -> WalletRead: ...
    def reserve(
        self, wallet_id: UUID, actor_id: int, values: JournalInput
    ) -> JournalReservation: ...
    def change_balance(self, change: BalanceChange, actor_id: int) -> int: ...
    def complete_entry(self, entry_id: UUID, observation: BalanceObservation) -> None: ...
    def read_entry(self, entry_id: UUID, customer_id: UUID, actor_id: int) -> JournalEntryRead: ...
    def search(self, values: JournalSearch) -> JournalPage: ...


class WalletCapability(Protocol):
    def open(self, values: WalletOpen) -> WalletOpening: ...
    def read(self, customer_id: UUID, actor_id: int) -> WalletRead: ...
    def change(self, values: WalletChange) -> WalletRead: ...
    def post(self, values: WalletPost) -> JournalEntryCreation: ...
    def read_entry(self, entry_id: UUID, customer_id: UUID, actor_id: int) -> JournalEntryRead: ...
    def search(self, values: JournalSearch) -> JournalPage: ...
