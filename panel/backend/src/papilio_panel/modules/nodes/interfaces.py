"""Node capabilities and native persistence/transport contracts."""

from typing import Protocol
from uuid import UUID

from .domain import (
    CertificateInput,
    IssuedCredentials,
    NodeConnection,
    NodeCreate,
    NodeCreation,
    NodeDefaults,
    NodePage,
    NodeRead,
    NodeSearch,
    NodeWorkKind,
    NodeWorkRead,
    ProbeObservation,
    WorkClaim,
    WorkCreation,
    WorkDelivery,
    WorkOutcome,
    WorkSubmission,
)


class NodeStorage(Protocol):
    def create(self, values: NodeCreate) -> NodeCreation: ...
    def read(self, node_id: UUID, actor_id: int) -> NodeRead: ...
    def search(self, values: NodeSearch) -> NodePage: ...
    def create_work(self, values: WorkSubmission) -> WorkCreation: ...
    def add_outbox(self, operation_id: UUID) -> None: ...
    def read_work(self, node_id: UUID, operation_id: UUID, actor_id: int) -> NodeWorkRead: ...
    def claim(self, operation_id: UUID, kind: NodeWorkKind) -> WorkClaim: ...
    def reject(self, operation_id: UUID, token: UUID, error_code: str) -> None: ...
    def finish_issue(self, claim: WorkClaim, credentials: IssuedCredentials) -> None: ...
    def finish_check(self, claim: WorkClaim, result: ProbeObservation) -> None: ...
    def credentials(self, node_id: UUID, actor_id: int) -> IssuedCredentials: ...
    def pending_deliveries(self) -> tuple[WorkDelivery, ...]: ...
    def mark_dispatched(self, deliveries: tuple[WorkDelivery, ...]) -> None: ...


class CertificateIssuer(Protocol):
    def issue(self, values: CertificateInput) -> IssuedCredentials: ...


class AgentGateway(Protocol):
    def check(self, connection: NodeConnection) -> ProbeObservation: ...


class BootstrapArchive(Protocol):
    def build(self, node: NodeRead, credentials: IssuedCredentials) -> bytes: ...


class NodeCapability(Protocol):
    def defaults(self, actor_id: int) -> NodeDefaults: ...
    def create(self, values: NodeCreate) -> NodeCreation: ...
    def read(self, node_id: UUID, actor_id: int) -> NodeRead: ...
    def search(self, values: NodeSearch) -> NodePage: ...
    def submit(self, values: WorkSubmission) -> NodeWorkRead: ...
    def read_work(self, node_id: UUID, operation_id: UUID, actor_id: int) -> NodeWorkRead: ...
    def bootstrap(self, node_id: UUID, actor_id: int) -> bytes: ...


class NodeExecutionCapability(Protocol):
    def issue(self, operation_id: UUID) -> WorkOutcome: ...
    def check(self, operation_id: UUID) -> WorkOutcome: ...


class NodePublicationCapability(Protocol):
    def dispatch(self) -> None: ...


class NodePublisher(Protocol):
    def publish(self, deliveries: tuple[WorkDelivery, ...]) -> None: ...
